//! Clipboard history: watch the general pasteboard for copied text.
//!
//! History lives in memory only (never written to disk). Copies that
//! password managers mark as concealed / transient are skipped
//! (http://nspasteboard.org conventions).

use objc2_app_kit::{NSPasteboard, NSPasteboardTypeString};
use objc2_foundation::NSString;

/// Bumps every time anything is copied (cheap to poll).
pub fn change_count() -> isize {
    NSPasteboard::generalPasteboard().changeCount()
}

/// The copied text, or None for non-text / concealed copies.
pub fn read() -> Option<String> {
    let pb = NSPasteboard::generalPasteboard();
    let types = pb.types()?;
    for t in types.iter() {
        let t = t.to_string();
        if matches!(
            t.as_str(),
            "org.nspasteboard.ConcealedType" | "org.nspasteboard.TransientType" | "org.nspasteboard.AutoGeneratedType"
        ) || t.starts_with("com.agilebits")
        {
            return None;
        }
    }
    let s = pb.stringForType(unsafe { NSPasteboardTypeString })?.to_string();
    if s.trim().is_empty() {
        return None;
    }
    // keep memory bounded for huge copies
    Some(if s.len() > 20_000 { s.chars().take(20_000).collect() } else { s })
}

/// Put text back on the clipboard; returns the new change count.
pub fn write(s: &str) -> isize {
    let pb = NSPasteboard::generalPasteboard();
    pb.clearContents();
    pb.setString_forType(&NSString::from_str(s), unsafe { NSPasteboardTypeString });
    pb.changeCount()
}

/// One line for the list: newlines → " ⏎ ", runs of spaces collapsed.
pub fn one_line(s: &str) -> String {
    let mut out = String::new();
    for (i, line) in s.trim().lines().map(str::trim).filter(|l| !l.is_empty()).enumerate() {
        if i > 0 {
            out.push_str("  ⏎  ");
        }
        out.extend(line.split_whitespace().collect::<Vec<_>>().join(" ").chars());
        if out.len() > 400 {
            break;
        }
    }
    out
}
